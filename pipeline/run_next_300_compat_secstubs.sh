#!/usr/bin/env bash

set -euo pipefail

: "${EVALUATION_ROOT:=$(pwd)}"

SELECTION="$EVALUATION_ROOT/benchmark/next-300-d2-secstub-selection.csv"

REFERENCE="${1:-$EVALUATION_ROOT/benchmark/policy/all.secstubs}"

EXISTING="${2:-$EVALUATION_ROOT/benchmark/next-300-d2-secstub-review/proposed/all.secstubs.before-candidate-generation}"

OUTPUT="${3:-$EVALUATION_ROOT/benchmark/next-300-d2-secstub-review/proposed/all.secstubs.candidate-generated}"

INVENTORY="${4:-$EVALUATION_ROOT/benchmark/next-300-d2-secstub-review/evidence/method-inventory.tsv}"

WORKSPACE_ROOT="$EVALUATION_ROOT/work/pilot"

if [[ ! -s "$SELECTION" ]]; then
    echo "ERROR: selection file is missing or empty: $SELECTION" >&2
    exit 2
fi

if [[ ! -s "$REFERENCE" ]]; then
    echo "ERROR: reference secstubs file is missing or empty: $REFERENCE" >&2
    exit 3
fi

if [[ ! -s "$EXISTING" ]]; then
    echo "ERROR: existing secstubs file is missing or empty: $EXISTING" >&2
    exit 4
fi

if [[ ! -s "$EVALUATION_ROOT/pipeline/build_compat_secstubs.py" ]]; then
    echo "ERROR: build_compat_secstubs.py is missing" >&2
    exit 5
fi

mkdir -p \
    "$(dirname "$OUTPUT")" \
    "$(dirname "$INVENTORY")"

mapfile -t CANDIDATE_IDS < <(
    python3 - "$SELECTION" <<'PY'
import csv
import sys

path = sys.argv[1]

with open(
    path,
    newline="",
    encoding="utf-8",
) as stream:
    rows = list(csv.DictReader(stream))

candidate_ids = [
    row["candidate_id"].strip()
    for row in rows
    if row.get("candidate_id", "").strip()
]

if len(candidate_ids) != len(set(candidate_ids)):
    raise SystemExit(
        "ERROR: duplicate candidate IDs in selection"
    )

for candidate_id in candidate_ids:
    print(candidate_id)
PY
)

if (( ${#CANDIDATE_IDS[@]} == 0 )); then
    echo "ERROR: no candidate IDs were loaded" >&2
    exit 6
fi

WORKSPACES=()
MISSING=()

for candidate_id in "${CANDIDATE_IDS[@]}"; do
    workspace="$WORKSPACE_ROOT/$candidate_id/D1/attempt-1/workspace"

    if [[ -d "$workspace" ]]; then
        WORKSPACES+=("$workspace")
    else
        MISSING+=("$candidate_id	$workspace")
    fi
done

printf 'Selected candidates: %d\n' \
    "${#CANDIDATE_IDS[@]}"

printf 'Existing D1 workspaces: %d\n' \
    "${#WORKSPACES[@]}"

printf 'Missing D1 workspaces: %d\n' \
    "${#MISSING[@]}"

missing_report="$EVALUATION_ROOT/benchmark/next-300-d2-secstub-review/evidence/missing-workspaces.tsv"

printf '%s\n' \
    "${MISSING[@]}" \
    > "$missing_report"

if (( ${#MISSING[@]} != 0 )); then
    echo "ERROR: one or more selected workspaces are missing" >&2
    echo "See: $missing_report" >&2
    exit 7
fi

if (( ${#WORKSPACES[@]} != 118 )); then
    echo "ERROR: expected 118 candidate workspaces, found ${#WORKSPACES[@]}" >&2
    exit 8
fi

checkpoint_dir="$EVALUATION_ROOT/benchmark/next-300-d2-secstub-review/evidence/checkpoints"
progress_file="$EVALUATION_ROOT/benchmark/next-300-d2-secstub-review/evidence/candidate-progress.tsv"

args=(
    "$EVALUATION_ROOT/pipeline/build_compat_secstubs.py"
    "${WORKSPACES[@]}"
    --reference "$REFERENCE"
    --existing "$EXISTING"
    --output "$OUTPUT"
    --inventory "$INVENTORY"
    --checkpoint-dir "$checkpoint_dir"
    --progress "$progress_file"
    --javap-timeout-seconds 30
    --candidate-timeout-seconds 600
    --class-progress-interval 100
)

printf 'Reference: %s\n' "$REFERENCE"
printf 'Existing:  %s\n' "$EXISTING"
printf 'Output:    %s\n' "$OUTPUT"
printf 'Inventory: %s\n' "$INVENTORY"

python3 "${args[@]}"

if [[ ! -s "$OUTPUT" ]]; then
    echo "ERROR: generator did not create a non-empty output file" >&2
    exit 9
fi

sha256sum \
    "$OUTPUT" \
    > "$EVALUATION_ROOT/benchmark/next-300-d2-secstub-review/evidence/candidate-generated.sha256"

printf 'Generated lines: '
wc -l < "$OUTPUT"

printf 'Generated bytes: '
wc -c < "$OUTPUT"

echo "Compatibility secstub generation complete"
